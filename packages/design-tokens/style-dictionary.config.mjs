import StyleDictionary from "style-dictionary";

const name = (token) => token.name;
const camel = (token) =>
  token.path.filter((p, i) => !(i === 0 && p === "color")).map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join("");
const px = (v) => String(v).replace(/px$/, "");

StyleDictionary.registerTransform({
  name: "name/sn",
  type: "name",
  transform: (token) => {
    const [a, b] = token.path;
    // Tailwind 4 theme namespaces: font sizes are --text-*, spacing is --spacing-*.
    if (a === "font" && b === "size") return ["text", ...token.path.slice(2)].join("-");
    if (a === "space") return ["spacing", ...token.path.slice(1)].join("-");
    return token.path.join("-");
  },
});

StyleDictionary.registerFormat({
  name: "css/tailwind-theme",
  format: ({ dictionary }) =>
    `/* GENERATED by style-dictionary. Do not edit. */\n@theme {\n${dictionary.allTokens
      .map((t) => `  --${name(t)}: ${t.$value};`)
      .join("\n")}\n}\n`,
});

export const dartFormat = ({ dictionary }) => {
    const lines = dictionary.allTokens.map((t) => {
      const id = t.path.join(".");
      if (t.$type === "color") {
        if (!/^#[0-9a-fA-F]{6}$/.test(t.$value))
          throw new Error(`Token ${id}: expected a 6-digit hex colour, got ${JSON.stringify(t.$value)}`);
        return `  static const Color ${camel(t)} = Color(0xFF${t.$value.slice(1).toUpperCase()});`;
      }
      if (t.$type === "dimension") {
        if (!/^\d+(\.\d+)?px$/.test(t.$value))
          throw new Error(`Token ${id}: expected a px dimension, got ${JSON.stringify(t.$value)}`);
        return `  static const double ${camel(t)} = ${px(t.$value)};`;
      }
      throw new Error(`Token ${id}: unsupported $type ${JSON.stringify(t.$type)}`);
    });
    return `// GENERATED by style-dictionary. Do not edit.\nimport 'dart:ui' show Color;\n\nabstract final class SnTokens {\n${lines.join("\n")}\n}\n`;
};

StyleDictionary.registerFormat({ name: "dart/sn-tokens", format: dartFormat });

/** Build config; `out` is the output root (default: committed build/). */
export const makeConfig = (out = "build/", source = "tokens.json") => ({
  source: [source],
  platforms: {
    css: {
      transforms: ["name/sn"],
      buildPath: `${out}css/`,
      files: [{ destination: "tokens.css", format: "css/tailwind-theme" }],
    },
    dart: {
      transforms: ["name/sn"],
      buildPath: `${out}dart/`,
      files: [{ destination: "tokens.dart", format: "dart/sn-tokens" }],
    },
  },
});

export default makeConfig();
